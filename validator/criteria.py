def criterion_label(key: str) -> str:
    if key in ALL_CRITERIA:
        name, ref, _ = ALL_CRITERIA[key]
        return f"{name} ({ref})"
    return key


def criteria_prompt_block(criteria: dict) -> str:
    return "\n".join(f"- `{k}` — {v[0]} [{v[1]}]: {v[2]}" for k, v in criteria.items())
